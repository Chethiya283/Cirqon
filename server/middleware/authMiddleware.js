const jwt = require("jsonwebtoken");
const User = require("../models/User");

/**
 * Authentication & Authorization Middleware
 * 
 * VIVA EXPLANATION:
 * 1. How Express Middleware Works:
 *    Middleware functions are pipeline interceptors in the HTTP request-response cycle
 *    with signature `(req, res, next)`. They can inspect incoming headers/body, perform
 *    cryptographic verification, enrich the request object (attaching `req.user`), and
 *    call `next()` to pass control to the route handler, or terminate early with an HTTP
 *    status code (401 Unauthorized or 403 Forbidden).
 * 
 * 2. JWT (JSON Web Token) Structure:
 *    A standard JWT consists of three Base64URL-encoded strings separated by dots:
 *    - Header: Specifies the token type and cryptographic algorithm (e.g. `{"alg":"HS256","typ":"JWT"}`).
 *    - Payload (Claims): Contains identity data (user `id`, `role`, issued-at `iat`, expiration `exp`).
 *    - Signature: Generated by running `HMAC-SHA256(base64Url(header) + "." + base64Url(payload), JWT_SECRET)`.
 *    Because the server secret is required to produce a valid signature, the server can statelessly
 *    verify the integrity and authenticity of the token without querying a session store on every call.
 * 
 * 3. requireAuth Guard:
 *    Extracts the Bearer token from the `Authorization` header, validates signature and expiration,
 *    and attaches the authenticated user record to `req.user`.
 * 
 * 4. requireAdmin Guard:
 *    Enforces Role-Based Access Control (RBAC). Rejects any request where `req.user.role !== "admin"`
 *    with HTTP 403 Forbidden.
 */

async function requireAuth(req, res, next) {
  try {
    const authHeader = req.headers.authorization;

    // 1. Verify Authorization header format: 'Bearer <token>'
    if (!authHeader || !authHeader.startsWith("Bearer ")) {
      return res.status(401).json({
        message: "Access denied. Authentication token required.",
      });
    }

    const token = authHeader.split(" ")[1];
    if (!token) {
      return res.status(401).json({
        message: "Access denied. Malformed authorization header.",
      });
    }

    // 2. Verify signature and expiration using server secret
    const decoded = jwt.verify(token, process.env.JWT_SECRET);

    // 3. Resolve user from database to ensure account is active and obtain up-to-date role
    const user = await User.findById(decoded.id).select("-passwordHash");
    if (!user) {
      return res.status(401).json({
        message: "Invalid token. User account does not exist.",
      });
    }

    // 4. Attach verified user to request object
    req.user = user;
    next();
  } catch (error) {
    if (error.name === "TokenExpiredError") {
      return res.status(401).json({
        message: "Authentication token has expired. Please log in again.",
      });
    }
    return res.status(401).json({
      message: "Invalid authentication token.",
    });
  }
}

function requireAdmin(req, res, next) {
  if (!req.user || req.user.role !== "admin") {
    return res.status(403).json({
      message: "Access forbidden. Administrator privileges required.",
    });
  }
  next();
}

module.exports = {
  requireAuth,
  requireAdmin,
};

